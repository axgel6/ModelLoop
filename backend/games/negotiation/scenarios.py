"""What is for sale in the Negotiation game.

Every scenario is a listing on an online marketplace and the seller behind it.
The buyer only ever talks to the seller by message. `opening` is the seller's
reply to the buyer's first "is this still available?", and it names the price
as {price}. No I/O in this file.
"""

LIKE_NEW = "Used - Like New"
GOOD = "Used - Good"
FAIR = "Used - Fair"
NEW = "New"
PARTS = "For parts"


def _listing(id, item, price, condition, seller, persona, description, opening, delivery="Local pickup", floor=None, swears=False,
             rude=False, repeats=False):
    """`floor` overrides how low the seller will go, as shares of the price: a rich seller who
    does not need the money takes far less than most. `rude`: their persona lets them take a jab
    at the buyer. `repeats`: they have a stock line or two and keep coming back to it."""
    return {
        "id": id, "item": item, "list_price": price, "condition": condition,
        "merchant": seller, "persona": persona, "description": description, "opening": opening,
        "setting": f"Marketplace · {delivery}",
        **({"floor_share": floor} if floor else {}),
        # An Unhinged seller: swears like a sailor, friendly underneath (see extras.SWEARING)
        **({"swears": True} if swears else {}),
        # Characters written to be cutting, or to say the same thing again (see extras.manner)
        **({"rude": True} if rude else {}),
        **({"repeats": True} if repeats else {}),
    }


def _scam(id, item, bait, real, condition, seller, persona, description, opening, payment, cover, delivery="Local pickup"):
    """A known scammer's listing: bait priced far under `real`, what the item really goes for.
    `payment` and `cover` are how they mean to get paid without handing anything over (see extras)."""
    return {**_listing(id, item, bait, condition, seller, persona, description, opening, delivery),
            "scam": {"payment": payment, "cover": cover}, "real_price": real}


